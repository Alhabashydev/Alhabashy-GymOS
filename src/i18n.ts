export const translations = { en, ar };

export function languageDirection(language: Language): 'ltr' | 'rtl' {
  return language === 'ar' ? 'rtl' : 'ltr';
}

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export function localizeMuscleGroup(language: Language, group: string): string {
  return translate(language, `muscle.${group}`);
}
